#import <Foundation/Foundation.h>
#import "WiredPadMac-Bridging-Header.h"

static void add(NSMutableData *data, const uint8_t *bytes, NSUInteger count) {
    [data appendBytes:bytes length:count];
}

NSData *WiredPadTouchReportDescriptor(void) {
    NSMutableData *descriptor = [NSMutableData data];
    const uint8_t beginning[] = {0x05,0x0D, 0x09,0x04, 0xA1,0x01, 0x85,0x01};
    add(descriptor, beginning, sizeof(beginning));
    for (int index = 0; index < 10; index++) {
        const uint8_t finger[] = {
            0x05,0x0D, 0x09,0x22, 0xA1,0x02,
            0x09,0x42, 0x09,0x32, 0x15,0x00, 0x25,0x01,
            0x75,0x01, 0x95,0x02, 0x81,0x02,
            0x75,0x06, 0x95,0x01, 0x81,0x03,
            0x09,0x51, 0x15,0x00, 0x25,0x09,
            0x75,0x08, 0x95,0x01, 0x81,0x02,
            0x05,0x01, 0x09,0x30, 0x09,0x31,
            0x16,0x00,0x00, 0x26,0xFF,0x7F,
            0x75,0x10, 0x95,0x02, 0x81,0x02,
            0xC0
        };
        add(descriptor, finger, sizeof(finger));
    }
    const uint8_t ending[] = {
        0x05,0x0D, 0x09,0x54, 0x15,0x00, 0x25,0x0A,
        0x75,0x08, 0x95,0x01, 0x81,0x02,
        0x09,0x55, 0x25,0x0A, 0xB1,0x02, 0xC0
    };
    add(descriptor, ending, sizeof(ending));
    return descriptor;
}

/// The Pencil, a digitizer pen with nothing else on the device, which the driver hands to
/// WindowServer as tablet events. Report 2 holds X and Y as 16.16 fixed point points on the
/// global display space.
NSData *WiredPadPenReportDescriptor(void) {
    const uint8_t pen[] = {
        0x05,0x0D, 0x09,0x02, 0xA1,0x01, 0x85,0x02,
        0x09,0x20, 0xA1,0x00,
        0x09,0x42, 0x09,0x44, 0x09,0x3C, 0x09,0x45, 0x09,0x32, // Tip, barrel, invert, eraser, in range
        0x15,0x00, 0x25,0x01, 0x75,0x01, 0x95,0x05, 0x81,0x02,
        0x75,0x03, 0x95,0x01, 0x81,0x03,
        0x05,0x01, 0x09,0x30, 0x09,0x31,
        0x17,0x00,0x00,0x00,0x80, 0x27,0xFF,0xFF,0xFF,0x7F, 0x75,0x20, 0x95,0x02, 0x81,0x02,
        0x05,0x0D, 0x09,0x30, 0x15,0x00, 0x26,0xFF,0x7F, 0x75,0x10, 0x95,0x01, 0x81,0x02, // Tip pressure
        0x09,0x3D, 0x09,0x3E, 0x15,0xA6, 0x25,0x5A, 0x75,0x08, 0x95,0x02, 0x81,0x02, // Tilt, degrees
        0x09,0x41, 0x15,0x00, 0x26,0xFF,0x59, 0x75,0x10, 0x95,0x01, 0x81,0x02, // Twist, 1/64 degree
        0xC0,
        // Report 3: the side of the Pencil was double-tapped.
        0x06,0x00,0xFF, 0x09,0x01, 0x85,0x03,
        0x15,0x00, 0x25,0x01, 0x75,0x01, 0x95,0x01, 0x81,0x02,
        0x75,0x07, 0x95,0x01, 0x81,0x03,
        0xC0
    };
    return [NSData dataWithBytes:pen length:sizeof(pen)];
}
